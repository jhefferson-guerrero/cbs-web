export interface Party {
  name: string
  logo?: string
  /** Logo muy compacto y de mucho peso visual (p. ej. el isotipo de CBS): se muestra un poco más pequeño. */
  logoSmall?: boolean
  /** Texto bajo el nombre; si son varias líneas (p. ej. el reparto de un consorcio), una por cada elemento. */
  note?: string | string[]
}

export interface GalleryImage {
  src: string
  /** Miniatura (400 px de ancho): la usan las miniaturas de la galería y de relleno mientras llega la foto grande. */
  thumb: string
  alt: string
}

export interface Project {
  slug: string
  category: string
  title: string
  location: string
  cover: string
  /** La portada en varios tamaños: la tarjeta de la Home la usa con `sizes` (un celular no necesita descargar ni decodificar la foto grande). La cabecera del proyecto usa `cover`. */
  coverSrcSet: string
  client: Party
  contractor: Party
  amount: string
  funding: Party
  gallery: GalleryImage[]
  /** Los logos de stakeholders y financiamiento son específicos de este proyecto (entidades de agua de Cusco). */
  showPartnerLogos?: boolean
}

